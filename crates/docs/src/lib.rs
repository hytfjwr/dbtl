//! The static Markdown documentation generator behind `dbtl docs --out <DIR>`.
//!
//! A pure transform: [`generate_docs`] turns a loaded [`Dag`] into a list of
//! `(relative path, Markdown contents)` pairs — one node page per node plus an
//! index `README.md`. The CLI layer (the `dbtl` binary) does the IO (create the
//! dir, write each file); this module never touches the filesystem or the
//! terminal, so it is unit-testable headlessly and reproducible byte-for-byte.
//!
//! Determinism is a hard requirement (the docs are meant to be committed and
//! `git diff`-checked in CI): every `HashSet`-sourced closure
//! ([`Dag::upstream`] / [`Dag::downstream`]) is sorted before use, node
//! iteration is over a sorted `unique_id` order, and per-node filenames are
//! assigned from a shared collision-avoidance map (the same approach as the
//! Mermaid node-id map) so two runs over the same `Dag` produce identical bytes.

use std::collections::{BTreeMap, HashSet};

use dbtl_core::layer::{first_dir, layer_rank};
use dbtl_core::mermaid::subgraph_mermaid_linked;
use dbtl_core::{
    column_coverage_counts, coverage_counts, in_package, Dag, Edge, Finding, LintRule, NodeInfo,
    PackageScope, Subgraph, LAYER_ORDER,
};

/// The subdirectory under `<out>` that holds every node page. The index
/// `README.md` sits at the root and links into here.
const NODES_DIR: &str = "models";

/// The first line of every generated file. An HTML comment (renders as
/// nothing) that marks the file as dbtl-owned: `docs --clean` deletes ONLY
/// files carrying this marker, and `docs --check` counts only marked on-disk
/// files as stale extras — a page a user wrote by hand is never removed or
/// flagged just for living under `<out>`. Exported so the CLI layer performs
/// the same identification byte-for-byte.
pub const GENERATED_MARKER: &str = "<!-- Generated by dbtl. Do not edit. -->";

/// Generate the full documentation set for `dag` as `(relative path, contents)`
/// pairs: one `models/<sanitized-uid>.md` per node and a single `README.md`
/// index. `project_name` titles the index; `source_label` records where the
/// data came from (a manifest path or a project dir) so a reader knows the
/// provenance; `scope` is the package scope the graph was loaded under — the
/// README states it verbatim so a committed doc set declares what it covers.
/// Pure and deterministic — see the module docs.
///
/// The lint-free entry point: no `Lint` summary or per-node violation sections
/// appear. [`generate_docs_with_findings`] renders them when the caller ran
/// [`dbtl_core::run_rules`].
pub fn generate_docs(
    dag: &Dag,
    project_name: &str,
    source_label: &str,
    scope: PackageScope,
) -> Vec<(String, String)> {
    generate_docs_with_findings(dag, project_name, source_label, scope, None)
}

/// [`generate_docs`] plus the static-lint readout: `findings` is the shared
/// [`dbtl_core::run_rules`] output (`Some`) — the SAME vector `dbtl check
/// --lint` gates on and the TUI's Lint lens/worklist quote — rendered as a
/// per-rule summary in the README and a per-node violation section on each
/// node's page. `None` means lint was not run: no lint output appears at all
/// (the distinction matters — a committed README must never claim "No
/// violations" for a check that never ran). `Some(&[])` means lint ran clean.
pub fn generate_docs_with_findings(
    dag: &Dag,
    project_name: &str,
    source_label: &str,
    scope: PackageScope,
    findings: Option<&[Finding]>,
) -> Vec<(String, String)> {
    // Assign every node a stable relative file path up front, so both the node
    // pages AND the README links resolve through the SAME map — a link can
    // never point at a file that was named differently (no broken links).
    let files = node_files(dag);

    // Findings grouped by node uid (each group's order is the run_rules rule
    // order — deterministic). `None` when lint didn't run → no section at all.
    let by_node: Option<BTreeMap<&str, Vec<&Finding>>> = findings.map(|fs| {
        let mut map: BTreeMap<&str, Vec<&Finding>> = BTreeMap::new();
        for f in fs {
            map.entry(f.node_uid.as_str()).or_default().push(f);
        }
        map
    });

    let mut out: Vec<(String, String)> = Vec::with_capacity(files.len() + 1);
    // Node pages in sorted unique_id order (deterministic write order). Every
    // file — node pages and the index alike — leads with GENERATED_MARKER so
    // `--clean`/`--check` can tell generated pages from hand-written ones.
    for (uid, rel_path) in &files {
        let node_findings = by_node
            .as_ref()
            .map(|m| m.get(uid.as_str()).cloned().unwrap_or_default());
        let body = node_markdown(dag, uid, &files, node_findings.as_deref());
        out.push((rel_path.clone(), format!("{GENERATED_MARKER}\n\n{body}")));
    }
    let index = readme_markdown(dag, project_name, source_label, &files, scope, findings);
    out.push((
        "README.md".to_string(),
        format!("{GENERATED_MARKER}\n\n{index}"),
    ));
    out
}

/// Assign each node a relative file path (`models/<sanitized-uid>.md`),
/// resolving collisions deterministically.
///
/// Sanitizing `unique_id` is lossy (`model.p.x_y` and `model.p_x.y` both
/// flatten to `model_p_x_y`), so two distinct uids could claim the same file
/// and silently overwrite each other. Mirroring [`dbtl_core::mermaid::mermaid_ids`],
/// uids are visited in sorted order (determinism) and a clashing stem gets the
/// first free `_2`, `_3`, … numeric suffix. The returned map is a `BTreeMap`,
/// so iterating it is itself in sorted-uid order.
fn node_files(dag: &Dag) -> BTreeMap<String, String> {
    let mut uids: Vec<&str> = dag.nodes().keys().map(String::as_str).collect();
    uids.sort_unstable();
    let mut used: HashSet<String> = HashSet::new();
    let mut files = BTreeMap::new();
    for uid in uids {
        let base = sanitize_stem(uid);
        let mut stem = base.clone();
        let mut n = 1usize;
        while !used.insert(stem.clone()) {
            n += 1;
            stem = format!("{base}_{n}");
        }
        files.insert(uid.to_string(), format!("{NODES_DIR}/{stem}.md"));
    }
    files
}

/// Sanitize a `unique_id` into a filesystem-safe file stem: every non
/// `[A-Za-z0-9._-]` char becomes `_`. The `.` separators in a uid are KEPT
/// (they read naturally as `model.project.name.md` and are filesystem-safe),
/// while `/`, spaces, quotes, and other hostile chars collapse to `_`. An empty
/// result falls back to `_` so the stem is never blank.
fn sanitize_stem(uid: &str) -> String {
    let stem: String = uid
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-') {
                c
            } else {
                '_'
            }
        })
        .collect();
    if stem.is_empty() {
        "_".to_string()
    } else {
        stem
    }
}

/// A relative link FROM a node page (in `models/`) TO another node's page. Both
/// live in the same directory, so the link is just the other file's basename.
fn link_between_nodes(target_rel_path: &str) -> &str {
    target_rel_path
        .rsplit('/')
        .next()
        .unwrap_or(target_rel_path)
}

