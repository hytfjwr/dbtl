#[test]
fn quiet_and_loud_write_identical_files() {
    // The `--quiet` flag changes ONLY stdout, never the generated bytes —
    // so the on-disk doc set is identical either way (the determinism contract
    // CI relies on).
    let loud = temp_out("det_loud");
    let quiet = temp_out("det_quiet");
    let _ = std::fs::remove_dir_all(&loud);
    let _ = std::fs::remove_dir_all(&quiet);
    assert!(run_docs(&loud, false).status.success());
    assert!(run_docs(&quiet, true).status.success());

    let readme_loud = std::fs::read(loud.join("README.md")).expect("loud README");
    let readme_quiet = std::fs::read(quiet.join("README.md")).expect("quiet README");
    assert_eq!(
        readme_loud, readme_quiet,
        "README bytes identical regardless of --quiet"
    );

    // And the same file set.
    let names = |dir: &PathBuf| {
        let mut v: Vec<String> = std::fs::read_dir(dir.join("models"))
            .expect("models dir")
            .filter_map(|e| e.ok())
            .map(|e| e.file_name().to_string_lossy().into_owned())
            .collect();
        v.sort();
        v
    };
    assert_eq!(names(&loud), names(&quiet), "same node-page file set");

    let _ = std::fs::remove_dir_all(&loud);
    let _ = std::fs::remove_dir_all(&quiet);
}

